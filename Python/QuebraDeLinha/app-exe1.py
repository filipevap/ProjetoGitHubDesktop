'''Quebra de linha
Utilizamos o código \n para inserir quebra de linha nos textos 
'''

print("Olá\nTudo bem?!\nMeu nome é Filipe")

'''Outra forma que temos de inserir a quebra de linha é colocando a string dentro de 3 aspas: """ """ . Vejamos:'''

print("""Olá
Tudo bem?!
Meu nome é Filipe.""")

'''Outra forma que temos de inserir a quebra de linha é inserindo vários prints. Vejamos:'''
print("Olá")
print("Tudo bem?!")
print("Meu nome é Filipe")

'''Outra forma que temos de inserir a quebra de linha é inserindo vários prints. Vejamos:'''
print("Olá", end=" ")
print("Tudo bem?")